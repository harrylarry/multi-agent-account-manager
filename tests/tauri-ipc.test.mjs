import assert from "node:assert/strict";
import { readFileSync, readdirSync } from "node:fs";
import { test } from "node:test";

const root = new URL("../src-tauri/", import.meta.url);
const read = (path) => readFileSync(new URL(path, root), "utf8");
const commandName = /^[a-z][a-z0-9_]*$/;

function list(source, pattern, itemPattern) {
  const block = source.match(pattern)?.[1];
  assert.ok(block, `Missing command list for ${pattern}`);
  return block.replace(/\/\/[^\n]*/g, "").split(",").map((line) => line.trim())
    .filter(Boolean).map((line) => {
      const command = line.match(itemPattern)?.[1];
      assert.ok(commandName.test(command ?? ""), `Unrecognized command: ${line}`);
      return command;
    });
}

test("all Tauri handlers have exact local-manager IPC grants", () => {
  const handlers = list(read("src/lib.rs"), /generate_handler!\s*\[([\s\S]*?)\]/, /^(?:\w+::)*(\w+)$/);
  const manifest = list(read("build.rs"), /const APP_COMMANDS[^=]*=\s*&\[([\s\S]*?)\]/, /^"(\w+)"$/);
  const capability = JSON.parse(read("capabilities/manager.json"));
  assert.equal(capability.local, true);
  assert.equal(capability.remote, undefined);
  assert.deepEqual(capability.windows.toSorted(), ["main", "manager"]);
  assert.deepEqual(capability.webviews, ["manager"]);
  const capabilities = readdirSync(new URL("capabilities/", root));
  assert.deepEqual(capabilities, ["manager.json"], "Review the trust scope of any additional capability");

  const permits = handlers.map((name) => `allow-${name.replaceAll("_", "-")}`);
  assert.deepEqual(manifest.toSorted(), handlers.toSorted(), "Registered commands must enter the app manifest");
  assert.deepEqual(capability.permissions.filter((id) => id.startsWith("allow-")).toSorted(),
    permits.toSorted(), "Each registered command must be allowed by the local manager capability");

  const directory = "permissions/autogenerated/";
  const files = readdirSync(new URL(directory, root)).filter((name) => name.endsWith(".toml"));
  assert.deepEqual(files.toSorted(), handlers.map((name) => `${name}.toml`).toSorted());
  for (const command of handlers) {
    const permission = command.replaceAll("_", "-");
    const definition = read(`${directory}${command}.toml`);
    for (const operation of ["allow", "deny"]) {
      const section = definition.split("[[permission]]").find((part) =>
        part.includes(`identifier = "${operation}-${permission}"`));
      assert.ok(section, `Missing ${operation} definition for ${command}`);
      assert.equal(section.match(/^commands\.(allow|deny)\s*=\s*\["([^"]+)"\]/m)?.slice(1).join(":"),
        `${operation}:${command}`);
    }
  }
});
